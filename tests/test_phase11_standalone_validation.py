def test_independent_geojson_validation():
    """Validates GeoJSON FeatureCollection independently according to RFC 7946."""
    for zip_path in [BHADLA_ZIP, BENCHMARK_ZIP]:
        with zipfile.ZipFile(zip_path, "r") as zf:
            geojson = json.loads(zf.read("change_clusters.geojson").decode("utf-8"))

            assert geojson["type"] == "FeatureCollection"
            assert "features" in geojson
            assert len(geojson["features"]) > 0

            for idx, feature in enumerate(geojson["features"]):
                assert feature["type"] == "Feature", f"Feature[{idx}] not Feature"
                assert "geometry" in feature
                geom = feature["geometry"]
                assert geom["type"] == "Polygon"

                coords = geom["coordinates"]
                assert isinstance(coords, list) and len(coords) >= 1
                ring = coords[0]
                assert len(ring) >= 4, f"Feature[{idx}] ring too small: {len(ring)}"

                # Closed ring check
                assert ring[0] == ring[-1], f"Feature[{idx}] ring not closed: {ring[0]} != {ring[-1]}"

                # WGS84 range check [lon, lat]
                for pt in ring:
                    lon, lat = pt[0], pt[1]
                    assert -180.0 <= lon <= 180.0, f"Lon {lon} outside [-180, 180]"
                    assert -90.0 <= lat <= 90.0, f"Lat {lat} outside [-90, 90]"

                # Properties check
                props = feature["properties"]
                assert "cluster_id" in props
                assert "classification" in props
                assert "confidence" in props
                assert "area_m2" in props
                assert "area_ha" in props
                assert "centroid" in props
                assert "source_scene_ids" in props
                assert "acquisition_dates" in props


def test_provenance_security_and_token_sanitization():
    """Inspects every exported artifact to guarantee zero leaked secrets or tokens."""
    forbidden_tokens = ["TEMP_SECRET_KEY", "TEMP_SIGNATURE_HASH", "token=", "sig=", "bearer", "process.env"]

    for zip_path in [BHADLA_ZIP, BENCHMARK_ZIP]:
        with zipfile.ZipFile(zip_path, "r") as zf:
            for name in zf.namelist():
                content = zf.read(name)
                # Check text files
                if name.endswith((".json", ".geojson", ".md", ".txt")):
                    text = content.decode("utf-8")
                    for token in forbidden_tokens:
                        assert token not in text, f"Found forbidden secret '{token}' in {name} of {zip_path}"

            # Verify public URLs retain useful scene identifiers while stripping tokens
            before_meta = json.loads(zf.read("before/scene_metadata.json").decode("utf-8"))
            preview_url = before_meta.get("preview_url", "")
            if preview_url:
                assert "item=" in preview_url, "preview_url must retain public item ID"
                assert "token=" not in preview_url, "preview_url must strip security token"


def test_bundle_portability():
    """Extracts bundle to clean directory and verifies standalone readability without TerraLens."""
    with tempfile.TemporaryDirectory() as tmpdir:
        with zipfile.ZipFile(BHADLA_ZIP, "r") as zf:
            zf.extractall(tmpdir)

        # 1. manifest.json standalone parse
        with open(os.path.join(tmpdir, "manifest.json"), "r", encoding="utf-8") as f:
            manifest = json.load(f)
            assert manifest["project_name"] == "TerraLens AI"
            assert manifest["problem_statement_id"] == "SIH26227"

        # 2. change_clusters.geojson standalone parse
        with open(os.path.join(tmpdir, "change_clusters.geojson"), "r", encoding="utf-8") as f:
            geojson = json.load(f)
            assert geojson["type"] == "FeatureCollection"

        # 3. README.md readability
        with open(os.path.join(tmpdir, "README.md"), "r", encoding="utf-8") as f:
            readme = f.read()
            assert "# TerraLens AI Analysis Report" in readme
            assert "## Quality & False-Alarm Controls" in readme
            assert "NOT calibrated probabilities" in readme

        # 4. provenance.json lineage readability
        with open(os.path.join(tmpdir, "provenance.json"), "r", encoding="utf-8") as f:
            prov = json.load(f)
            assert prov["lineage_standard"] == "TerraLens Structured Auditable Lineage"
            assert "blockchain" not in json.dumps(prov).lower()
