def test_zip_integrity_and_artifacts():
    """Verify ZIP opens, central directory is valid, no duplicates, all required artifacts present."""
    assert os.path.exists(BHADLA_ZIP), f"Missing {BHADLA_ZIP}"
    assert os.path.exists(BENCHMARK_ZIP), f"Missing {BENCHMARK_ZIP}"

    for zip_path in [BHADLA_ZIP, BENCHMARK_ZIP]:
        with zipfile.ZipFile(zip_path, "r") as zf:
            # Test central directory / corruption
            corrupt = zf.testzip()
